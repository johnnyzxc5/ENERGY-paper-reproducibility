function run_reproduction()
%RUN_REPRODUCTION Recompute and check the frozen annual reference results.
% Run from the repository root with: matlab -batch "run_reproduction"
% The original numerical model is preserved in code/ESP2.m.

root = fileparts(mfilename('fullpath'));
outputFolder = fullfile(root, 'results', 'generated');
referenceFolder = fullfile(root, 'results', 'reference');
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end
validationFile = fullfile(outputFolder, 'validation.json');
if isfile(validationFile)
    delete(validationFile);
end

oldFolder = pwd;
oldPath = path;
cleanup = onCleanup(@() restoreSession(oldFolder, oldPath)); %#ok<NASGU>
addpath(fullfile(root, 'code'));
cd(outputFolder);

% The separate workspace protects this runner from the legacy script's clear.
data = evaluateOriginalModel();
Region = compose("R%d", (1:6)');

energy = table(Region, data.Annual_E_wt_50m, data.Annual_E_wt_100m, ...
    'VariableNames', {'region', 'energy_50m_kwh', 'energy_100m_kwh'});
hydrogen = table(Region, data.Annual_H2_50m, data.Annual_EXC_50m, ...
    data.Annual_H2_100m, data.Annual_EXC_100m, 'VariableNames', ...
    {'region', 'hydrogen_50m_kg', 'surplus_50m_kwh', ...
    'hydrogen_100m_kg', 'surplus_100m_kwh'});
economics = table(Region, data.C_elc_50m, data.C_H2_50m, ...
    data.C_elc_100m, data.C_H2_100m, 'VariableNames', ...
    {'region', 'electricity_50m_usd_per_kwh', 'hydrogen_50m_usd_per_kg', ...
    'electricity_100m_usd_per_kwh', 'hydrogen_100m_usd_per_kg'});

writetable(energy, fullfile(outputFolder, 'annual_energy.csv'));
writetable(hydrogen, fullfile(outputFolder, 'annual_hydrogen_surplus.csv'));
writetable(economics, fullfile(outputFolder, 'economic_results.csv'));

% One row per region and month, with both turbine configurations side by side.
[regionIndex, monthIndex] = ndgrid(1:6, 1:12);
monthly = table(compose("R%d", regionIndex(:)), monthIndex(:), ...
    data.E_wt_50m(:), data.E_wt_100m(:), ...
    data.m_H2_50m(:), data.m_H2_100m(:), ...
    data.E_EXC_50m(:), data.E_EXC_100m(:), ...
    'VariableNames', {'region', 'month', 'energy_50m_kwh', 'energy_100m_kwh', ...
    'hydrogen_50m_kg', 'hydrogen_100m_kg', 'surplus_50m_kwh', 'surplus_100m_kwh'});
writetable(monthly, fullfile(outputFolder, 'monthly_results.csv'));
save(fullfile(outputFolder, 'model_results.mat'), '-struct', 'data');

% Reference CSVs retain the precision of the historical exported tables.
maxEnergyError = compareReference(energy, ...
    fullfile(referenceFolder, 'annual_energy.csv'), 0.0050001);
maxHydrogenError = compareReference(hydrogen, ...
    fullfile(referenceFolder, 'annual_hydrogen_surplus.csv'), 0.0050001);
maxEconomicError = compareReference(economics, ...
    fullfile(referenceFolder, 'economic_results.csv'), 0.0005001);

assert(all(isfinite(table2array(energy(:, 2:end))), 'all'), ...
    'Energy results must be finite.');
assert(all(isfinite(table2array(hydrogen(:, 2:end))), 'all'), ...
    'Hydrogen and surplus results must be finite.');
assert(all(isfinite(table2array(economics(:, 2:end))), 'all'), ...
    'Economic results must be finite.');
assert(all(data.m_H2_50m >= 0 & data.m_H2_100m >= 0, 'all'), ...
    'Hydrogen production must be nonnegative.');
assert(all(data.E_EXC_50m >= 0 & data.E_EXC_100m >= 0, 'all'), ...
    'Exported energy must be nonnegative.');
assert(max(abs(data.E_wt_50m - 50 * data.m_H2_50m - data.E_EXC_50m), ...
    [], 'all') < 1e-8, '50 m monthly energy balance failed.');
assert(max(abs(data.E_wt_100m - 50 * data.m_H2_100m - data.E_EXC_100m), ...
    [], 'all') < 1e-8, '100 m monthly energy balance failed.');
assert(all(data.m_H2_50m <= data.E_e / 50 + 1e-10, 'all') && ...
    all(data.m_H2_100m <= data.E_e / 50 + 1e-10, 'all'), ...
    'Monthly electrolyzer capacity exceeded.');

report = struct('status', 'PASS', 'matlab_version', version, ...
    'matlab_release', version('-release'), ...
    'max_energy_reference_error', maxEnergyError, ...
    'max_hydrogen_surplus_reference_error', maxHydrogenError, ...
    'max_economic_reference_error', maxEconomicError, ...
    'energy_reference_tolerance_kwh', 0.0050001, ...
    'hydrogen_surplus_reference_tolerance', 0.0050001, ...
    'economic_reference_tolerance', 0.0005001, ...
    'monthly_energy_balance', 'PASS', 'electrolyzer_capacity', 'PASS');
fid = fopen(validationFile, 'w');
assert(fid ~= -1, 'Could not open validation report.');
fileCleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s\n', jsonencode(report, 'PrettyPrint', true));

fprintf('\nPASS: all annual reference tables and monthly balance checks match.\n');
fprintf('Generated results: %s\n', outputFolder);
end

function data = evaluateOriginalModel()
ESP2;
data = struct('Power_All_50', Power_All_50, 'Power_All_100', Power_All_100, ...
    'E_wt_50m', E_wt_50m, 'E_wt_100m', E_wt_100m, 'E_e', E_e, ...
    'm_H2_50m', m_H2_50m, 'm_H2_100m', m_H2_100m, ...
    'E_EXC_50m', E_EXC_50m, 'E_EXC_100m', E_EXC_100m, ...
    'Annual_E_wt_50m', Annual_E_wt_50m, 'Annual_E_wt_100m', Annual_E_wt_100m, ...
    'Annual_H2_50m', Annual_H2_50m, 'Annual_H2_100m', Annual_H2_100m, ...
    'Annual_EXC_50m', Annual_EXC_50m, 'Annual_EXC_100m', Annual_EXC_100m, ...
    'C_elc_50m', C_elc_50m, 'C_elc_100m', C_elc_100m, ...
    'C_H2_50m', C_H2_50m, 'C_H2_100m', C_H2_100m, ...
    'Ingresos_Excedentes_50m', Ingresos_Excedentes_50m, ...
    'Ingresos_Excedentes_100m', Ingresos_Excedentes_100m);
end

function maxError = compareReference(actual, referenceFile, tolerance)
expected = readtable(referenceFile, 'TextType', 'string');
assert(isequal(actual.Properties.VariableNames, expected.Properties.VariableNames), ...
    'Reference column mismatch: %s', referenceFile);
assert(isequal(actual.region, expected.region), ...
    'Reference region mismatch: %s', referenceFile);
errors = abs(table2array(actual(:, 2:end)) - table2array(expected(:, 2:end)));
assert(all(isfinite(errors), 'all'), 'Nonfinite reference error: %s', referenceFile);
maxError = max(errors, [], 'all');
assert(maxError <= tolerance, ...
    'Reference mismatch in %s: maximum error %.12g exceeds %.12g.', ...
    referenceFile, maxError, tolerance);
end

function restoreSession(oldFolder, oldPath)
cd(oldFolder);
path(oldPath);
end
